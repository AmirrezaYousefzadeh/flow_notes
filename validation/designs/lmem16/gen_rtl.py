# Regenerates rtl/bmi_snn_lmem16.v: the logic of BCI_paper's sw/gen_variant.py (commit cc819ec) for one variant, with
# bmi_snn_lmem2g's entry and H = 16. Reads <bci root>/rtl/bmi_snn_par.v only (the project's generator writes into the
# project). For H = 64 it reproduces the lmem2g validation RTL (git 37c170b) byte for byte (checked 2026-11-03).
# Usage: python3 gen_rtl.py <bci root> [name H out.v]     (default: bmi_snn_lmem16 16 rtl/bmi_snn_lmem16.v)
import re, sys
from pathlib import Path

root = Path(sys.argv[1])
name, H, out = (sys.argv[2], int(sys.argv[3]), Path(sys.argv[4])) if len(sys.argv) > 4 else \
    ("bmi_snn_lmem16", 16, Path(__file__).resolve().parent / "rtl/bmi_snn_lmem16.v")
src = "bmi_snn_par.v"
prm = dict(H=H, HARDWIRED=0, V_BITS=20, O_BITS=24, DENSE=1)          # bmi_snn_lmem2g's entry, H replaced
defs = ["LATCH_MEM", "GATE_DP", "W2_PIPE"]


def latch_icgs(H):
    L = ["  // integrated clock gates of the latch memory (generated by sw/gen_variant.py): one per W1 row, one per W2 word"]
    L += [f"  sky130_fd_sc_hd__dlclkp_1 u_icg_r{c} (.CLK(wr_clk), .GATE(row_we_q1[{c}]), .GCLK(row_gclk[{c}]));" for c in range(97)]
    L += [f"  sky130_fd_sc_hd__dlclkp_1 u_icg_j{j} (.CLK(wr_clk), .GATE(w2_we_q1[{j}]), .GCLK(w2_gclk[{j}]));" for j in range(H)]
    return "\n".join(L)


s = (root / "rtl" / src).read_text()
s, n = re.subn(r"module bmi_snn_(par|top) #\(", f"module {name} #(", s); assert n == 1
for k, v in prm.items():
    s, n = re.subn(rf"(parameter integer {k}\s*=\s*)\d+", rf"\g<1>{v}", s)
    assert n == 1, (name, k)
defs = list(defs)
if "LATCH_MEM" in defs:
    defs.append("LATCH_ICG_GENERATED")
    assert "//@@LATCH_ICG@@" in s
    s = s.replace("  //@@LATCH_ICG@@", latch_icgs(prm["H"]))
head = f"// GENERATED by sw/gen_variant.py from rtl/{src} — do not edit; variant {name}: {prm} {defs}\n"
head += "".join(f"`define {d}\n" for d in defs)
out.write_text(head + s)
print("wrote", out, prm, defs)
