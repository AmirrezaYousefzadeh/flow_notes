#!/usr/bin/env bash
# Harden a sky130 validation design with LibreLane under the measurement settings of the sky130 notes (5.1) and the
# hardening policy (5.3): tools/harden_ladder.sh over the design's utilisations, accepted only when the 9-corner own
# sign-off passes (sky130_signoff.sh). Designs with SRAM22 macros are synthesised first, for the standard-cell area of
# their absolute floorplan (tools/macro_config.py, one utilisation).
# Usage: sky130_harden.sh <design dir> <work dir>
# Result: <work dir>/runs/accepted, <work dir>/ladder.json, <work dir>/harden.json; exit status 0 when accepted.
set -euo pipefail
[[ $# -eq 2 ]] || { sed -n '6p' "$0"; exit 2; }
source "$(dirname "$0")/env.sh"
load_design "$1"
mkdir -p "$2"; WORK="$(cd "$2" && pwd)"
CFG="$WORK/config.yaml"

yaml_list() { python3 -c 'import json,sys; print(json.dumps(sys.argv[1:]))' "$@"; }
INC_LINE=""; [[ ${#INCDIRS[@]} -eq 0 ]] || INC_LINE="VERILOG_INCLUDE_DIRS: $(yaml_list "${INCDIRS[@]}")"
cat > "$CFG" <<EOF
# generated by flow_notes/validation/flow/sky130_harden.sh for $NAME: the measurement settings of sky130 notes 5.1
DESIGN_NAME: $TOP
VERILOG_FILES: $(yaml_list "${RTL[@]}")
$INC_LINE
VERILOG_DEFINES: $(yaml_list "${SYNTH_DEFINES[@]}")
CLOCK_PORT: $CLOCK_PORT
CLOCK_PERIOD: $CLOCK_NS
PNR_SDC_FILE: $SDC
SIGNOFF_SDC_FILE: $SDC
STD_CELL_LIBRARY: sky130_fd_sc_hd
STA_THREADS: 2
FP_SIZING: relative
FP_CORE_UTIL: 50
DECAP_CELLS: []
RUN_HEURISTIC_DIODE_INSERTION: false
DIODE_ON_PORTS: none
RUN_ANTENNA_REPAIR: false
DRT_ANTENNA_REPAIR_ITERS: 0
GRT_ALLOW_CONGESTION: true
PL_RESIZER_HOLD_MAX_BUFFER_PCT: 80
GRT_RESIZER_HOLD_MAX_BUFFER_PCT: 80
DESIGN_REPAIR_BUFFER_INPUT_PORTS: false
DESIGN_REPAIR_BUFFER_OUTPUT_PORTS: false
EXTRA_EXCLUDED_CELLS: ["sky130_fd_sc_hd__clkdlybuf4s*"]
EOF
# the design's own settings: a key the flow already wrote is replaced, not duplicated
CONFIG_EXTRA="$CONFIG_EXTRA" python3 - "$CFG" <<'PY'
import os, re, sys
cfg = sys.argv[1]
extra = [l for l in os.environ.get("CONFIG_EXTRA", "").splitlines() if l.strip()]
keys = {re.match(r"(\w+)\s*:", l).group(1) for l in extra if re.match(r"\w+\s*:", l)}
lines = [l for l in open(cfg).read().splitlines() if l.strip() and not any(l.startswith(k + ":") for k in keys)]
open(cfg, "w").write("\n".join(lines + ([f"# design-specific ({len(extra)} lines)"] + extra if extra else [])) + "\n")
PY

if [[ -n "${MACRO_INSTANCES:-}" ]]; then
  read -r -a U_LIST <<< "$UTILS"
  [[ ${#U_LIST[@]} -eq 1 ]] || { echo "a macro design takes one utilisation (absolute floorplan)"; exit 2; }
  echo "==== $NAME: synthesis first, for the standard-cell area of the macro floorplan  ($(date '+%F %H:%M'))"
  cp "$CFG" "$WORK/config_synth.yaml"
  python3 "$TOOLS/macro_config.py" "$WORK/config_synth.yaml" "$SRAM22" "$MACRO_CELL" $MACRO_INSTANCES --synthesis-only
  ( cd "$WORK" && _OPENLANE_MAX_CORES="$THREADS" in_librelane python3 -m librelane -j "$THREADS" \
      --pdk-root "$PDK_ROOT" --pdk "$PDK" --manual-pdk --run-tag synth --overwrite --to Yosys.Synthesis \
      config_synth.yaml ) > "$WORK/synth.log" 2>&1 || { tail -n 20 "$WORK/synth.log"; exit 1; }
  STD_AREA=$(python3 -c 'import glob,json,sys; s=glob.glob(sys.argv[1]+"/runs/synth/*-yosys-synthesis/state_out.json")[0]
print(json.load(open(s))["metrics"]["design__instance__area"])' "$WORK")
  echo "   standard-cell area after synthesis: $STD_AREA µm²"
  python3 "$TOOLS/macro_config.py" "$CFG" "$SRAM22" "$MACRO_CELL" $MACRO_INSTANCES \
    --std-area "$STD_AREA" --utilisation "${U_LIST[0]}"
fi

export DESIGN_DIR="$D" SIGNOFF_CMD="$FLOW/sky130_signoff.sh" LIBRELANE PDK_ROOT PDK
status=0
"$TOOLS/harden_ladder.sh" "$CFG" "$WORK" "$UTILS" || status=$?
[[ $status -eq 0 ]] || { echo "$NAME: no utilisation accepted (see $WORK/ladder.json)"; exit 1; }

python3 - "$WORK" "$(versions_json)" <<'PY'
import glob, json, sys
work, versions = sys.argv[1], json.loads(sys.argv[2])
run = f"{work}/runs/accepted"
m = json.load(open(f"{run}/final/metrics.json"))
so = json.load(open(f"{run}/signoff/signoff.json"))
ladder = json.load(open(f"{work}/ladder.json"))
taps = m.get("design__instance__count__class:tap_cell", 0)
summary = {
    "accepted_utilisation_pct": ladder["accepted_utilisation_pct"], "attempts": ladder["attempts"],
    "cells": m.get("design__instance__count__stdcell", 0) - taps, "tap_cells": taps,
    "cell_area_um2": m.get("design__instance__area__stdcell"), "core_area_um2": m.get("design__core__area"),
    "hold_buffers": m.get("design__instance__count__hold_buffer"),
    "repair_buffers": m.get("design__instance__count__class:timing_repair_buffer"),
    "setup_ws_ns": so["setup_ws_ns"], "hold_ws_ns": so["hold_ws_ns"], "signoff_corners": len(so["corners"]),
    "drc_errors": m.get("route__drc_errors"), "power_grid_violations": m.get("design__power_grid_violation__count"),
    "antenna_violating_nets": m.get("antenna__violating__nets"), "versions": versions}
json.dump(summary, open(f"{work}/harden.json", "w"), indent=1)
print(json.dumps({k: v for k, v in summary.items() if k not in ("attempts", "versions")}))
PY
